def test_authenticated_synthetic_request_reaches_authorization_logic():
    """Verify authenticated request via SyntheticPrincipal executes authorization branches."""
    vuln_app = SyntheticApp("test-app", vulnerable_variant=True)
    patched_app = SyntheticApp("test-app", vulnerable_variant=False)

    principal_b = SyntheticPrincipal(identity_id="user_b", is_authenticated=True)

    # Vulnerable allows cross-identity access -> 200
    status_v, body_v = vuln_app.handle_request(
        "GET",
        "/api/v1/invoices/INV-100",
        authenticated_principal=principal_b,
    )
    assert status_v == 200
    assert body_v["invoice"]["id"] == "INV-100"
    assert body_v["invoice"]["owner"] == "user_a"

    # Patched blocks cross-identity access -> 403
    status_p, body_p = patched_app.handle_request(
        "GET",
        "/api/v1/invoices/INV-100",
        authenticated_principal=principal_b,
    )
    assert status_p == 403
    assert "Access forbidden" in body_p["error"]


def test_unauthenticated_request_returns_401():
    """Verify unauthenticated request returns 401 across protected routes."""
    app = SyntheticApp("test-app", vulnerable_variant=True)

    # 1. No principal, no header
    status, body = app.handle_request("GET", "/api/v1/invoices/INV-100")
    assert status == 401
    assert "Authentication required" in body["error"]

    # 2. Principal with is_authenticated=False
    unauth_principal = SyntheticPrincipal(identity_id="user_a", is_authenticated=False)
    status, body = app.handle_request(
        "GET",
        "/api/v1/invoices/INV-100",
        authenticated_principal=unauth_principal,
    )
    assert status == 401

    # 3. Header with redacted marker without principal
    status, body = app.handle_request(
        "GET",
        "/api/v1/invoices/INV-100",
        headers={"Authorization": "Bearer ******"},
    )
    assert status == 401

    # 4. Header with simulated placeholder without principal
    status, body = app.handle_request(
        "GET",
        "/api/v1/invoices/INV-100",
        headers={"Authorization": "Bearer [REDACTED_SIM_TOKEN_FOR_user_a]"},
    )
    assert status == 401


def test_vulnerable_and_patched_variants_produce_intended_authorization_behavior():
    """Verify intended authorization behavior across application families."""
    # SaaS Billing BOLA
    app_v = SyntheticApp("app", vulnerable_variant=True)
    app_p = SyntheticApp("app", vulnerable_variant=False)
    p_b = SyntheticPrincipal(identity_id="user_b")

    st_v, _ = app_v.handle_request("GET", "/api/v1/invoices/INV-100", authenticated_principal=p_b)
    st_p, _ = app_p.handle_request("GET", "/api/v1/invoices/INV-100", authenticated_principal=p_b)
    assert st_v == 200
    assert st_p == 403

    # Tenant isolation on subscriptions
    st_v_sub, _ = app_v.handle_request("GET", "/api/v1/subscriptions/SUB-100", authenticated_principal=p_b)
    st_p_sub, _ = app_p.handle_request("GET", "/api/v1/subscriptions/SUB-100", authenticated_principal=p_b)
    assert st_v_sub == 200
    assert st_p_sub == 403

    # Step skipping on orders refund
    p_a = SyntheticPrincipal(identity_id="user_a")
    st_v_ord, _ = app_v.handle_request("POST", "/api/v1/orders/ORD-001/refund", authenticated_principal=p_a)
    st_p_ord, _ = app_p.handle_request("POST", "/api/v1/orders/ORD-001/refund", authenticated_principal=p_a)
    assert st_v_ord == 200
    assert st_p_ord == 400

    # Role privilege elevation
    st_v_role, _ = app_v.handle_request("POST", "/api/v1/users/user_a/roles", authenticated_principal=p_a)
    st_p_role, _ = app_p.handle_request("POST", "/api/v1/users/user_a/roles", authenticated_principal=p_a)
    assert st_v_role == 200
    assert st_p_role == 403


def test_redacted_evidence_remains_secret_free():
    """Verify CanonicalEvidence generated by simulator contains zero raw secret tokens."""
    sim = HeadlessSimulator()
    app = SyntheticApp("app", vulnerable_variant=True)

    exp = ExperimentProposal(
        objective="Verify BOLA without leaking credentials",
        target_asset_id="ASSET-INV",
        mutation_class=MutationClass.CROSS_IDENTITY_REPLAY,
        actor_identity_id="user_b",
        target_identity_id="user_a",
        expected_observations=ExpectedObservations(
            supporting_observation="Returns HTTP 200 with victim invoice",
            contradicting_observation="Returns HTTP 403 Forbidden",
        ),
    )

    res = sim.execute_experiment(exp, app)
    assert res.status_code == 200
    assert res.observation_type == "SUPPORTING"

    raw_tokens = ["token_a", "token_b", "token_admin"]
    evidence_text = f"{res.evidence_item.statement} {res.evidence_item.response_body_summary}"
    for token in raw_tokens:
        assert token not in evidence_text, f"Raw secret token '{token}' leaked in evidence!"


def test_simulator_identity_cannot_be_arbitrarily_elevated():
    """Verify caller role is authoritatively resolved from user store, preventing forged elevation."""
    patched_app = SyntheticApp("app", vulnerable_variant=False)

    # user_a claims to call admin endpoint
    principal_user = SyntheticPrincipal(identity_id="user_a", is_authenticated=True)
    status, body = patched_app.handle_request(
        "POST",
        "/api/v1/users/user_a/roles",
        authenticated_principal=principal_user,
    )
    # Patched app checks registered role (customer), which is not admin -> 403
    assert status == 403
    assert "Admin role required" in body["error"]

    # Legitimate admin succeeds
    principal_admin = SyntheticPrincipal(identity_id="admin_user", is_authenticated=True)
    status_admin, _ = patched_app.handle_request(
        "POST",
        "/api/v1/users/user_a/roles",
        authenticated_principal=principal_admin,
    )
    assert status_admin == 200


